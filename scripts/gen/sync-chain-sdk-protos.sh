#!/usr/bin/env bash
# sync-chain-sdk-protos.sh — Vendor Akash .proto sources from chain-sdk into
# akash-deploy-rs/proto/akash for prost generation (just gen-proto).
#
# Layout (deliberate):
#   chain-sdk/proto/node/akash/**      → proto/akash/**   (chain modules: deploy, market, …)
#   chain-sdk/proto/provider/akash/**  → proto/akash/**   (overlay: manifest, inventory, provider RPC)
#
# Not touched:
#   proto/console/**          — Console API (Zod → proto)
#   proto/rust-vendored/**    — cosmos / ibc / gogo include tree
#   proto/vendor/**           — go mod vendor (k8s Quantity); use `just modvendor`
#
# Usage:
#   ./scripts/gen/sync-chain-sdk-protos.sh
#   CHAIN_SDK_DIR=/path/to/chain-sdk ./scripts/gen/sync-chain-sdk-protos.sh
#   ./scripts/gen/sync-chain-sdk-protos.sh --check   # exit 1 if tree drifts
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PROTO_DIR="${ROOT}/proto"
AKASH_DST="${PROTO_DIR}/akash"
PIN_FILE="${PROTO_DIR}/CHAIN_SDK_PIN"

# Default: sibling checkout under terp-core/crates/
DEFAULT_SDK="$(cd "${ROOT}/.." && pwd)/chain-sdk"
CHAIN_SDK_DIR="${CHAIN_SDK_DIR:-${DEFAULT_SDK}}"

CHECK_ONLY=0
if [[ "${1:-}" == "--check" ]]; then
  CHECK_ONLY=1
fi

die() { echo "error: $*" >&2; exit 1; }

[[ -d "${CHAIN_SDK_DIR}" ]] || die "chain-sdk not found at ${CHAIN_SDK_DIR} (set CHAIN_SDK_DIR)"

NODE_SRC="${CHAIN_SDK_DIR}/proto/node/akash"
PROV_SRC="${CHAIN_SDK_DIR}/proto/provider/akash"
[[ -d "${NODE_SRC}" ]] || die "missing ${NODE_SRC}"
[[ -d "${PROV_SRC}" ]] || die "missing ${PROV_SRC}"

command -v rsync >/dev/null || die "rsync required"

pin_meta() {
  local rev="unknown" desc="unknown" date="unknown"
  if git -C "${CHAIN_SDK_DIR}" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    rev="$(git -C "${CHAIN_SDK_DIR}" rev-parse HEAD 2>/dev/null || echo unknown)"
    desc="$(git -C "${CHAIN_SDK_DIR}" describe --tags --always 2>/dev/null || echo unknown)"
    date="$(git -C "${CHAIN_SDK_DIR}" log -1 --format=%cI 2>/dev/null || echo unknown)"
  fi
  cat <<EOF
# Auto-generated by scripts/gen/sync-chain-sdk-protos.sh — do not hand-edit.
# Identifies which chain-sdk tree was last synced into proto/akash/.
chain_sdk_dir=${CHAIN_SDK_DIR}
git_sha=${rev}
git_describe=${desc}
git_date=${date}
synced_at=$(date -u +%Y-%m-%dT%H:%M:%SZ)
node_proto_files=$(find "${NODE_SRC}" -name '*.proto' | wc -l | tr -d ' ')
provider_proto_files=$(find "${PROV_SRC}" -name '*.proto' | wc -l | tr -d ' ')
EOF
}

sync_tree() {
  echo ">>> chain-sdk: ${CHAIN_SDK_DIR}"
  echo ">>> dest:      ${AKASH_DST}"

  # Fresh tree so deleted upstream protos disappear (no stale packages).
  rm -rf "${AKASH_DST}"
  mkdir -p "${AKASH_DST}"

  # 1) Node modules (deployment, market, escrow, cert, …)
  rsync -a --delete \
    --exclude '.DS_Store' \
    "${NODE_SRC}/" "${AKASH_DST}/"

  # 2) Provider overlay (manifest, inventory, provider lease/status) —
  #    same package path prefix `akash/…`, must share one tree for imports.
  rsync -a \
    --exclude '.DS_Store' \
    "${PROV_SRC}/" "${AKASH_DST}/"

  pin_meta > "${PIN_FILE}"

  local n
  n=$(find "${AKASH_DST}" -name '*.proto' | wc -l | tr -d ' ')
  echo ">>> synced ${n} .proto files under proto/akash/"
  echo ">>> pin written to proto/CHAIN_SDK_PIN"
  cat "${PIN_FILE}"
}

check_drift() {
  local tmp drift_file
  tmp="$(mktemp -d)"
  drift_file="$(mktemp)"
  # Clean temp dirs on any exit path from this function (avoid EXIT trap + set -u).
  cleanup_check() {
    rm -rf "${tmp}"
    rm -f "${drift_file}"
  }

  mkdir -p "${tmp}/akash"
  rsync -a --exclude '.DS_Store' "${NODE_SRC}/" "${tmp}/akash/"
  rsync -a --exclude '.DS_Store' "${PROV_SRC}/" "${tmp}/akash/"

  if ! diff -rq "${tmp}/akash" "${AKASH_DST}" >"${drift_file}" 2>&1; then
    echo "proto/akash is out of date vs ${CHAIN_SDK_DIR}" >&2
    head -40 "${drift_file}" >&2
    echo "…" >&2
    echo "Run: just sync-protos && just gen-proto" >&2
    cleanup_check
    exit 1
  fi
  cleanup_check
  echo "proto/akash matches chain-sdk (${CHAIN_SDK_DIR})"
}

if [[ "${CHECK_ONLY}" -eq 1 ]]; then
  [[ -d "${AKASH_DST}" ]] || die "proto/akash missing — run just sync-protos"
  check_drift
  exit 0
fi

sync_tree

# Remind operators about k8s vendor (include path only).
if [[ ! -d "${PROTO_DIR}/vendor/k8s.io" ]]; then
  echo ""
  echo "note: proto/vendor/k8s.io not found — run \`just modvendor\` before gen-proto"
  echo "      (k8s Quantity is required by inventory/provider status protos)"
fi

echo ""
echo "Next: just modvendor   # if k8s vendor missing"
echo "      just gen-proto    # prost → src/gen/"
echo "      just gen-console  # optional Console API clients"
echo "      just py-gen       # optional Python bindings"
